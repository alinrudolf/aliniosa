"""Regenerate contactMapGeometry.ts with Python 3 from Natural Earth land and lakes."""

import json
import math
from pathlib import Path
from urllib.request import urlopen


SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/'
WIDTH, HEIGHT = 1760, 716
LATITUDE_STEP = 0.82
LONGITUDE_SPACING = 9

# Longitude, latitude, and radii in degrees. The footprints stay on existing land dots.
HOTSPOTS = {
    'pacific-coast': (-123, 39, 7.0, 4.9),
    'britain': (-3, 53, 6.0, 3.4),
    'atlantic-coast': (-81, 35, 6.0, 5.0),
    'western-europe': (-1, 46, 5.0, 3.6),
    'central-europe': (13, 50, 5.8, 3.7),
    'northern-europe': (16, 60, 5.6, 4.0),
}


def polygons(name):
    with urlopen(f'{SOURCE}ne_110m_{name}.geojson', timeout=30) as response:
        features = json.load(response)['features']

    for feature in features:
        geometry = feature['geometry']
        parts = geometry['coordinates']
        for outline, *holes in (parts if geometry['type'] == 'MultiPolygon' else [parts]):
            longitudes, latitudes = zip(*outline)
            bounds = (min(longitudes), max(longitudes), min(latitudes), max(latitudes))
            yield bounds, outline, holes


def contains(ring, lon, lat):
    inside = False
    previous_lon, previous_lat = ring[-1]
    for next_lon, next_lat in ring:
        if (previous_lat > lat) != (next_lat > lat):
            crossing = next_lon + (previous_lon - next_lon) * (lat - next_lat) / (previous_lat - next_lat)
            if lon < crossing:
                inside = not inside
        previous_lon, previous_lat = next_lon, next_lat
    return inside


def covers(shapes, lon, lat):
    return any(
        west <= lon <= east and south <= lat <= north
        and contains(outline, lon, lat)
        and not any(contains(hole, lon, lat) for hole in holes)
        for (west, east, south, north), outline, holes in shapes
    )


def equatorial_x(lon):
    # Spread the Atlantic so the two shores frame the centered Contact panel.
    return 4.7 * (lon + 45) + 430 * math.tanh((lon + 42) / 30)


def project(lon, lat):
    # Converging meridians and bowed parallels create the tilted display.
    north = lat - 42
    east = equatorial_x(lon) * (1 - 0.008 * north) + 1.5 * north
    return WIDTH / 2 + east, 325 - 10.9 * north - 0.000052 * east**2 - 0.06 * east


def longitude_columns():
    for offset in range(-1080, 1081, LONGITUDE_SPACING):
        west, east = -165, 100
        for _ in range(19):
            middle = (west + east) / 2
            if equatorial_x(middle) < offset:
                west = middle
            else:
                east = middle
        yield (west + east) / 2


def grid_path():
    parallels = [[project(lon, lat) for lon in range(-165, 101, 5)] for lat in range(-20, 81, 10)]
    meridians = [[project(lon, lat) for lat in range(-25, 86, 5)] for lon in range(-160, 91, 10)]
    return ''.join(
        'M' + ' '.join(f'{x:.1f} {y:.1f}' for x, y in line)
        for line in parallels + meridians
    )


def generate():
    land = list(polygons('land'))
    lakes = list(polygons('lakes'))
    columns = list(longitude_columns())
    # Round SVG stroke caps draw the dots without a separate element for each point.
    dots = {3: [], 3.7: [], 4.2: []}
    hotspots = {name: [] for name in HOTSPOTS}

    for row in range(math.ceil(-25 / LATITUDE_STEP), math.floor(85 / LATITUDE_STEP) + 1):
        lat = row * LATITUDE_STEP
        size = 3 if lat >= 57 else 3.7 if lat >= 30 else 4.2
        for lon in columns:
            x, y = project(lon, lat)
            if not (-8 <= x <= WIDTH + 8 and -8 <= y <= HEIGHT + 8):
                continue
            if not covers(land, lon, lat) or covers(lakes, lon, lat):
                continue

            dot = f'M{x:.1f} {y:.1f}h.01'
            dots[size].append(dot)
            for name, (center_lon, center_lat, radius_lon, radius_lat) in HOTSPOTS.items():
                if ((lon - center_lon) / radius_lon)**2 + ((lat - center_lat) / radius_lat)**2 <= 1:
                    hotspots[name].append(dot)

    output = [
        '// Generated by generate_contact_map.py from Natural Earth 1:110m land and lakes (public domain).',
        f"export const contactMapViewBox = '0 0 {WIDTH} {HEIGHT}';",
        f"export const contactMapGrid = '{grid_path()}';",
        'export const contactMapDots = [',
    ]
    output.extend(f"  {{ width: {width}, path: '{''.join(path)}' }}," for width, path in dots.items())
    output.extend(['];', 'export const contactMapHotspots = {'])
    output.extend(f"  '{name}': '{''.join(path)}'," for name, path in hotspots.items())
    output.extend(['} as const;', ''])
    Path(__file__).with_name('contactMapGeometry.ts').write_text('\n'.join(output), encoding='utf-8', newline='\n')
    print(f'{sum(map(len, dots.values()))} land dots', {name: len(path) for name, path in hotspots.items()})


if __name__ == '__main__':
    generate()
